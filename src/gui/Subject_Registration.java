    public void loadSubjects() {

        try {
            ResultSet rs = Mysql.search("SELECT * FROM `subject`");

            DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
            dtm.setRowCount(0);

            while (rs.next()) {

                Vector v = new Vector();
                v.add(rs.getString("subject.Subno"));
                v.add(rs.getString("subject.description"));
                v.add(rs.getString("subject.Price"));

                dtm.addRow(v);

            }
            jTable1.setModel(dtm);

        } catch (Exception e) {
            e.printStackTrace();
        }

    }

    public void loadSubjects(String text) {

        try {
            ResultSet rs = Mysql.search("SELECT * FROM `subject`  WHERE `subject`.`Description` LIKE '" + text + "%'  ORDER BY `subject`.`Subno` ASC  ");

            DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
            dtm.setRowCount(0);

            while (rs.next()) {

                Vector v = new Vector();
                v.add(rs.getString("subject.Subno"));
                v.add(rs.getString("subject.description"));
                v.add(rs.getString("subject.Price"));

                dtm.addRow(v);

            }
            jTable1.setModel(dtm);

        } catch (Exception e) {
            e.printStackTrace();
        }

    }
    
    
