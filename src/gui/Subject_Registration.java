    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        String Sub_des = jTextField1.getText();
        String price = jTextField2.getText();

        if (Sub_des.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter Subject Description", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (price.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter price", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (!Pattern.compile("([1-9][0-9]*)|(([1-9][0-9]*)[.]([0]*[1-9][0-9]*))|([0][.]([0]*[1-9][0-9]*))").matcher(price).matches()) {
            JOptionPane.showMessageDialog(this, "Invalid your price", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {

            try {

                Mysql.iud("INSERT INTO `subject`(`Description`,`Price`)VALUES('" + Sub_des + "','" + price + "')");

//                this.dispose();
                add_sub a = new add_sub();
                a.setVisible(true);
                loadSubjects();

            } catch (Exception e) {
                e.printStackTrace();
            }

        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jTextField2KeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_jTextField2KeyTyped

        String price = jTextField2.getText();
        String text = price + evt.getKeyChar();

        if (!Pattern.compile("(0|0[.]|0[.][0-9]*)|[1-9]|[1-9][0-9]*|[1-9][0-9]*[.]|[1-9][0-9]*[.][0-9]*").matcher(text).matches()) {
            evt.consume();
        }

    }//GEN-LAST:event_jTextField2KeyTyped

    private void jButton6ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton6ActionPerformed

        int r = jTable1.getSelectedRow();

        if (r == -1) {
            JOptionPane.showMessageDialog(this, "Please select subject", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {

            int option = JOptionPane.showConfirmDialog(this, "Do you want to remove this subject?", "Confirmation", JOptionPane.YES_NO_OPTION, JOptionPane.INFORMATION_MESSAGE);

            if (option == JOptionPane.YES_OPTION) {

                try {
                    String sid = jTable1.getValueAt(r, 0).toString();
                    System.out.println(sid);
                    Mysql.iud("DELETE FROM `subject` WHERE `Subno`='" + sid + "'");

                } catch (Exception e) {
                    e.printStackTrace();
                }

                DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
                dtm.removeRow(r);

                JOptionPane.showMessageDialog(this, "subject removed", "Success", JOptionPane.INFORMATION_MESSAGE);

            }
        }

    }//GEN-LAST:event_jButton6ActionPerformed

    private void jButton7ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton7ActionPerformed

        int r = jTable1.getSelectedRow();

        if (r == -1) {
            JOptionPane.showMessageDialog(this, "Please select subject", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {

            int option = JOptionPane.showConfirmDialog(this, "Do you want to update this subject?", "Confirmation", JOptionPane.YES_NO_OPTION, JOptionPane.INFORMATION_MESSAGE);

            if (option == JOptionPane.YES_OPTION) {

                try {
                    String subid = jTable1.getValueAt(r, 0).toString();
                    String subname = jTextField1.getText();
                    String price = jTextField2.getText();

                    System.out.println(subid);
                    Mysql.iud("UPDATE `subject` SET `Description`= '" + subname + "',`Price`= '" + price + "' WHERE `Subno`='" + subid + "'");

                } catch (Exception e) {
                    e.printStackTrace();
                }

                DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
                loadSubjects();
                resetfield();
                JOptionPane.showMessageDialog(this, "subject updated", "Success", JOptionPane.INFORMATION_MESSAGE);

            }
        }

    }//GEN-LAST:event_jButton7ActionPerformed

