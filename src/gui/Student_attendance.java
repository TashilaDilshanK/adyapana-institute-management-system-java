    public void studenttable() {

        try {
            ResultSet rs = Mysql.search("SELECT * FROM `student attendance` ");

            DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
            dtm.setRowCount(0);

            while (rs.next()) {

                Vector v = new Vector();
                v.add(rs.getString("student attendance.Sno"));
                v.add(rs.getString("student attendance.class_no"));
                v.add(rs.getString("student attendance.A_date"));
                v.add(rs.getString("student attendance.attend"));

                dtm.addRow(v);

            }
            jTable1.setModel(dtm);

        } catch (Exception e) {
            e.printStackTrace();
        }

    }

