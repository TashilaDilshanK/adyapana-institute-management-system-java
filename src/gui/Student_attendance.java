    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        String sno = jComboBox1.getSelectedItem().toString();
        String cno = jComboBox2.getSelectedItem().toString();
        Date attend_d = jDateChooser1.getDate();
        String d = sdf.format(attend_d);

        if (sno.equals("Select")) {
            JOptionPane.showMessageDialog(this, "Please select student", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (cno.equals("Select")) {
            JOptionPane.showMessageDialog(this, "Please select class", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (attend_d == null) {
            JOptionPane.showMessageDialog(this, "Please enter date", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {

            Mysql.iud("INSERT INTO `student attendance`(`Sno`,`Class_no`,`A_Date`,`attend`)VALUES('" + sno + "','" + cno + "','" + d + "','present')");

            studenttable();
            JOptionPane.showMessageDialog(this, "Attendance Marked", "Success", JOptionPane.INFORMATION_MESSAGE);
        }

    }//GEN-LAST:event_jButton1ActionPerformed

    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked

        if (evt.getClickCount() == 2) {
            int r = jTable1.getSelectedRow();

            if (r == -1) {
                JOptionPane.showMessageDialog(this, "Please select a Student", "Success", JOptionPane.INFORMATION_MESSAGE);

            } else {

                String id = jTable1.getValueAt(r, 0).toString();
                String attend = jTable1.getValueAt(r, 3).toString();

                if (attend.equals("present")) {

                    Mysql.iud("UPDATE `student attendance` SET `attend`= 'absent' WHERE `Sno`='" + id + "'");
                    studenttable();

                }

            }
        }

    }//GEN-LAST:event_jTable1MouseClicked

