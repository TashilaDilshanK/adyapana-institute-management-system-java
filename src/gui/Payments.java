    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed

        String paymentType = jComboBox1.getSelectedItem().toString();
        String payment = jTextField3.getText();

        if (jTable1.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Please select class", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (paymentType.equals("Select")) {
            JOptionPane.showMessageDialog(this, "Please select payment method", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (!Pattern.compile("(0|0[.]|0[.][0-9]*)|[1-9]|[1-9][0-9]*|[1-9][0-9]*[.]|[1-9][0-9]*[.][0-9]*").matcher(payment).matches()) {
            JOptionPane.showMessageDialog(this, "Invalid payment", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {

            try {
                String filepath = "src//report//adyapanai.jrxml";
                JasperReport jr = JasperCompileManager.compileReport(filepath);

                HashMap parameters = new HashMap();
                parameters.put("Parameter1", jLabel6.getText().toString());
                parameters.put("Parameter2", jLabel5.getText().toString());
                parameters.put("Parameter3", jLabel20.getText().toString());
                parameters.put("Parameter4", jTextField3.getText().toString());
                parameters.put("Parameter5", jLabel24.getText().toString());

                Connection datasource = Mysql.getConnection();
                TableModel tm = jTable1.getModel();
                JRTableModelDataSource dataSource = new JRTableModelDataSource(tm);

                JasperPrint jp = JasperFillManager.fillReport(jr, parameters, datasource);

                JasperViewer.viewReport(jp, false);

                String sid = jLabel6.getText();
                String tname = jLabel12.getText();
                String subn = jLabel9.getText();
                int mon = jMonthChooser1.getMonth() + 1;
                String price = jLabel16.getText();

                ResultSet rs = Mysql.search("SELECT `tno` FROM `teacher` WHERE `First_name` = '" + tname + "'");
                rs.next();
                String tno = rs.getString("tno");
                ResultSet rs1 = Mysql.search("SELECT `subno` FROM `subject` WHERE `Description` = '" + subn + "'");
                rs1.next();
                String subno = rs1.getString("subno");

                Mysql.iud("INSERT INTO `invoice`(`Student_Sno`,`Teacher_Tno`,`Subno`,`Month`,`Price`)VALUES('" + sid + "','" + tno + "','" + subno + "','" + mon + "','" + price + "')");

                Mysql.iud("INSERT INTO `invoice_print`(`class id`,`subject name`,`teacher name`,`month`,`payment`)VALUES('" + subno + "','" + subn + "','" + tname + "','" + mon + "','" + price + "')");

            } catch (Exception e) {
                e.printStackTrace();
            }

        }

    }//GEN-LAST:event_jButton5ActionPerformed

