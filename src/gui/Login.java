    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        char passwordArray[] = jPasswordField1.getPassword();
        String password = String.valueOf(passwordArray);

        if (jTextField2.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Plese enter your username", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Plese enter your password", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {

            String username = jTextField2.getText();

            try {
                ResultSet resultset = Mysql.search("SELECT * FROM `login` WHERE `Username`='" + username + "' AND `Password`='" + password + "' ");
                if (resultset.next()) {
//                  JOptionPane.showMessageDialog(this, "Sign In Success","Success",JOptionPane.INFORMATION_MESSAGE);

                    Dashboard home = new Dashboard();
                    home.setVisible(true);
                    this.dispose();

                } else {
                    JOptionPane.showMessageDialog(this, "Invalid Username or Password", "Warning", JOptionPane.WARNING_MESSAGE);
                }

            } catch (Exception e) {
                e.printStackTrace();
            }

        }
    }//GEN-LAST:event_jButton1ActionPerformed

